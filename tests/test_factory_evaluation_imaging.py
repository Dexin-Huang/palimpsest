def _registry() -> MetricRegistry:
    registry = MetricRegistry()
    register_imaging_metrics(registry)
    return registry


def _gold(station: str) -> dict[str, object]:
    path = EVALUATION_ROOT / "gold" / station / GOLD_FILES[station]
    return json.loads(path.read_text(encoding="utf-8"))


def test_imaging_metrics_distinguish_adjudicated_good_and_damaged_fixtures() -> None:
    registry = _registry()
    observed_names: set[str] = set()

    for station in STATIONS:
        gold = _gold(station)
        assert gold["rights"] == "CC0-1.0; generated by the Palimpsest test suite"
        assert str(gold["fixture_method"]).startswith("deterministic_")
        good = gold["good_output"]
        broken = gold["broken_output"]
        assert isinstance(good, dict) and isinstance(broken, dict)

        station_metrics = [
            metric for metric in registry.all() if metric.name.startswith(f"{station}_")
        ]
        assert station_metrics
        for metric in station_metrics:
            good_value = metric.observe(good, gold)
            broken_value = metric.observe(broken, gold)
            observed_names.add(metric.name)
            assert good_value is not None, metric.name
            assert 0.0 <= good_value <= 1.0, metric.name
            if broken_value is not None:
                assert -1.0 <= broken_value <= 1.0, metric.name
                if metric.name != "flatten_geometry_preservation":
                    if metric.direction is MetricDirection.MAXIMIZE:
                        assert good_value >= broken_value, metric.name
                    else:
                        assert good_value <= broken_value, metric.name

    assert observed_names == set(registry.by_name)

    flatten_gold = _gold("flatten")
    wrong_size = {"pixels": [[128]], "source_sha256": flatten_gold["source_sha256"]}
    assert (
        registry.observe("flatten_geometry_preservation", wrong_size, flatten_gold)
        == 0.0
    )

    align_gold = _gold("align")
    shifted = copy.deepcopy(align_gold["good_output"])
    shifted["columns"][0]["chars"][0]["bbox"] = [17, 4, 5, 6]
    assert registry.observe("align_coordinate_error", shifted, align_gold) > 0.0

    wrong_lines = copy.deepcopy(align_gold["good_output"])
    chars = [char for column in wrong_lines["columns"] for char in column["chars"]]
    wrong_lines["columns"] = [
        {"bbox": [22, 4, 5, 6], "chars": chars[:1]},
        {"bbox": [9, 5, 18, 15], "chars": chars[1:]},
    ]
    line_score = registry.observe(
        "align_line_association_accuracy", wrong_lines, align_gold
    )
    assert line_score is not None and line_score < 1.0


def test_undefined_imaging_denominators_are_unknown_and_omissions_are_failures() -> (
    None
):
    registry = _registry()

    empty_regions = {"route": "blank", "regions": []}
    for name in (
        "segment_region_precision",
        "segment_region_recall",
        "segment_mean_intersection_over_union",
        "segment_region_intersection_recall",
        "segment_marginalia_recall",
        "segment_reading_order_accuracy",
        "segment_protected_completeness",
        "segment_false_blank_page_rate",
    ):
        assert registry.observe(name, empty_regions, empty_regions) is None, name

    one_expected = {
        "route": "segmented",
        "regions": [
            {
                "region_id": "r00",
                "kind": "body",
                "bbox": [1, 1, 5, 5],
                "reading_order": 0,
                "protected": True,
            }
        ],
    }
    no_predictions = {"route": "blank", "regions": []}
    assert (
        registry.observe("segment_region_precision", no_predictions, one_expected)
        is None
    )
    assert (
        registry.observe("segment_region_recall", no_predictions, one_expected) == 0.0
    )
    assert (
        registry.observe("segment_protected_completeness", no_predictions, one_expected)
        == 0.0
    )
    assert (
        registry.observe("segment_false_blank_page_rate", no_predictions, one_expected)
        == 1.0
    )

    no_unmatched = {
        "image_size": [20, 20],
        "columns": [{"chars": [{"ch": "A", "bbox": [1, 1, 4, 4]}]}],
    }
    assert (
        registry.observe("align_unmatched_character_recall", no_unmatched, no_unmatched)
        is None
    )

    unbound_candidate = {"columns": [{"chars": [{"ch": "A", "bbox": None}]}]}
    bound_gold = {
        "image_size": [20, 20],
        "columns": [{"chars": [{"ch": "A", "bbox": [1, 1, 4, 4]}]}],
    }
    assert (
        registry.observe("align_character_box_precision", unbound_candidate, bound_gold)
        is None
    )
    assert (
        registry.observe("align_character_box_recall", unbound_candidate, bound_gold)
        == 0.0
    )
    assert (
        registry.observe(
            "align_fabricated_coordinate_rate", unbound_candidate, bound_gold
        )
        is None
    )

    ambiguous_columns = {
        "image_size": [20, 20],
        "columns": [
            {"chars": [{"ch": "A", "bbox": [1, 1, 4, 4]}]},
            {"chars": [{"ch": "A", "bbox": [10, 1, 4, 4]}]},
        ],
    }
    assert (
        registry.observe(
            "align_column_order_accuracy", ambiguous_columns, ambiguous_columns
        )
        is None
    )


def test_image_artifact_observation_localizes_reencoded_crop(tmp_path: Path) -> None:
    rng = np.random.default_rng(4101)
    source = rng.integers(0, 256, size=(180, 240, 3), dtype=np.uint8)
    source_path = tmp_path / "source.jpg"
    assert cv2.imwrite(str(source_path), source, [cv2.IMWRITE_JPEG_QUALITY, 95])
    decoded_source = cv2.imread(str(source_path), cv2.IMREAD_COLOR)
    assert decoded_source is not None
    output_path = tmp_path / "output.jpg"
    output = decoded_source[17:159, 23:211]
    assert cv2.imwrite(str(output_path), output, [cv2.IMWRITE_JPEG_QUALITY, 92])

    source_sha256 = hashlib.sha256(source_path.read_bytes()).hexdigest()
    observation = image_artifact_observation(
        output_path,
        source_path,
        source_sha256=source_sha256,
    )

    assert observation["source_bbox"] == [23, 17, 188, 142]
    assert observation["source_sha256"] == source_sha256
    assert np.asarray(observation["pixels"]).shape == (142, 188, 3)


def test_image_artifact_observation_rejects_unreadable_output(tmp_path: Path) -> None:
    source_path = tmp_path / "source.jpg"
    output_path = tmp_path / "output.jpg"
    source_path.write_bytes(b"not an image")
    output_path.write_bytes(b"also not an image")

    with pytest.raises(ValueError, match="output is not a readable image"):
        image_artifact_observation(
            output_path,
            source_path,
            source_sha256="0" * 64,
        )


def test_imaging_resources_load_strictly_with_real_hashes_and_actual_sockets() -> None:
    registry = _registry()
    loaded: dict[str, tuple[object, object]] = {}

    for station in STATIONS:
        candidate = load_candidate(
            FACTORY_ROOT / "candidates" / station / "current.yaml"
        )
        suite = load_suite(
            EVALUATION_ROOT / "suites" / station / "conformance-v1.yaml",
            metric_resolver=registry,
            probe_resolver={},
            judge_resolver={},
        )
        validate_candidate_suite(candidate, suite)
        loaded[station] = candidate, suite

        assert candidate.station == suite.station == station
        assert candidate.variant == "default"
        assert candidate.model is None and candidate.prompt_name is None
        assert suite.promotion.minimum_completed_cases == len(suite.cases) == 1
        assert suite.judges == () and suite.downstream_probes == ()
        assert suite.qualification_eligible is False
        assert suite.promotion.require_all_downstream_probes is False
        assert all(metric.minimum_effect == 0.0 for metric in suite.primary_metrics)
        for metric in suite.primary_metrics:
            assert metric.direction == registry.get(metric.name).direction.value

        case = suite.cases[0]
        expected_inputs = {
            "deframe": {"page_image"},
            "dewatermark": {"page_image_framed"},
            "flatten": {"page_image_unmarked"},
            "segment": {"page_image_clean"},
            "align": {"page_image_clean", "page_transcription"},
        }[station]
        assert set(case.inputs) == expected_inputs
        assert set(case.references) == {"metric_gold"}
        assert case.license == "CC0-1.0"
        assert case.adjudication == {
            "method": "deterministic_fixture_geometry",
            "version": 1,
        }

        for asset in (*case.inputs.values(), *case.references.values()):
            assert not isinstance(asset, dict)
            assert asset.path is not None
            path = EVALUATION_ROOT / asset.path
            assert hashlib.sha256(path.read_bytes()).hexdigest() == asset.sha256

    with pytest.raises(RecordError, match="does not match suite station"):
        validate_candidate_suite(loaded["deframe"][0], loaded["segment"][1])


